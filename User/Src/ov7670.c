void OV7670_Init()
{
	OV7670_Write_Reg(0x12, 0x80);
  HAL_Delay(200);
  for (int i = 0; ov7670_qvga_rgb565[i][0] != 0xff; i++) {
    OV7670_Write_Reg(ov7670_qvga_rgb565[i][0], ov7670_qvga_rgb565[i][1]);
  }
    
}